const TYPE_HEADERS: Record<Post["type"], string> = {
  tip:      "💡 <b>Совет дня</b>",
  fact:     "📊 <b>Интересный факт</b>",
  quote:    "💬 <b>Цитата</b>",
  case:     "🎯 <b>Из жизни</b>",
  question: "❓ <b>Вопрос дня</b>",
};

const HASHTAGS: Record<Post["type"], string> = {
  tip:      "#советдня #финансы #займы",
  fact:     "#факт #деньги #психология",
  quote:    "#цитата #мудрость #деньги",
  case:     "#изжизни #опыт #займы",
  question: "#вопрос #подумать #финансы",
};

/**
 * Returns a formatted Telegram HTML post for the given day index.
 * dayIndex = 0-based day of year (0..364). Cycles through POSTS array.
 */
export function getChannelPost(dayIndex: number): string {
  const post = POSTS[dayIndex % POSTS.length];
  const header = TYPE_HEADERS[post.type];
  const tags = HASHTAGS[post.type];

  return (
    `${header}\n\n` +
    `${post.body}\n\n` +
    `${tags}\n` +
    `👉 @zaymy_bot — учёт займов между друзьями`
  );
}

