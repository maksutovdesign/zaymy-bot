/** Returns one random tip for the given context */
export function getAdvisorTip(context: AdvisorContext): string {
  const list = TIPS[context];
  return list[Math.floor(Math.random() * list.length)];
}

/** Returns `count` unique random tips picked from the entire tips pool */
export function getRandomTips(count: number): string[] {
  const all: string[] = [];
  for (const list of Object.values(TIPS)) {
    all.push(...list);
  }

  // Fisher-Yates shuffle on a copy, then take first `count`
  const shuffled = [...all];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, Math.min(count, shuffled.length));
}
